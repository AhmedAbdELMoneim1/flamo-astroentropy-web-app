from groq import Groq
from PIL import Image

client = Groq()

def groq_chat(model, messages, max_tokens=600, retries=4):
    for i in range(retries):
        try:
            r = client.chat.completions.create(model=model, messages=messages, temperature=0.1, max_tokens=max_tokens)
            return r.choices[0].message.content.strip()
        except Exception as e:
            wait = 2 ** (i + 1)
            print(f"  [groq retry {i+1}/{retries}] {type(e).__name__}: {str(e)[:120]} -> sleep {wait}s")
            time.sleep(wait)
    return ""

def pil_to_data_url(img: Image.Image, max_side=1200) -> str:
    img = img.convert("RGB")
    img.thumbnail((max_side, max_side))
    buf = io.BytesIO(); img.save(buf, format="JPEG", quality=88)
    return "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode()


