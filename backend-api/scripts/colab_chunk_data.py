TABLE_PROMPT = """Below is a table from a scientific paper on microgravity combustion and fire safety.
Write a SHORT description (max 3 sentences) that helps a search engine find this table:
what it contains, how it is organized (meaning of rows/columns, materials or fuels, test conditions such as
gravity level, O2 concentration, pressure, flow velocity, sample geometry), the units, the platform or
facility if it appears in the context, and one key takeaway (e.g. which condition gives the highest spread
rate or the lowest flammability limit).

Rules:
- Use ONLY information present in the table, caption or context. If a unit, condition or column meaning is not
  stated, say it is not stated. Do not guess.
- Do NOT list all the values (the full table is attached separately).
- Keep symbols, units and material names exactly as written.
- Same language as the table.

Paper: {doc}
Context before the table: {context}
Caption: {caption}

TABLE:
{table}"""

def describe_table(md_table: str, caption: str = "", doc_title: str = "", context: str = "") -> str:
    prompt = TABLE_PROMPT.format(doc = doc_title, context=context, caption=caption, table=md_table)
    return groq_chat(TEXT_MODEL, [{"role": "user", "content": prompt}], max_tokens=400)

def describe_image(img: Image.Image, caption: str = "", context: str = "", doc: str = "") -> dict:
    msgs = [{"role": "user", "content": [
        {"type": "text", "text": IMAGE_PROMPT.format(doc=doc, caption=caption, context=context)},
        {"type": "image_url", "image_url": {"url": pil_to_data_url(img)}},
    ]}]
    raw = groq_chat(VLM_MODEL, msgs, max_tokens=650)
    t = re.search(r"TYPE:\s*(\S+)", raw)
    s = re.search(r"SUMMARY:\s*(.*)", raw, re.S)
    return {"type": t.group(1).strip().lower() if t else "unknown",
            "summary": s.group(1).strip() if s else raw}

from langchain_text_splitters import RecursiveCharacterTextSplitter
from docling_core.types.doc import (DocItemLabel, TitleItem, SectionHeaderItem,
                                    TableItem, PictureItem, TextItem)

TABLE_MAX_CHARS = 4000

splitter = RecursiveCharacterTextSplitter(
    chunk_size=CHUNK_SIZE, chunk_overlap=CHUNK_OVERLAP,
    separators=["\n\n", "\n", ". ", "؟ ", "! ", " ", ""],
)

SKIP_LABELS = (DocItemLabel.PAGE_FOOTER, DocItemLabel.CAPTION)

def page_of(item):
    return item.prov[0].page_no if getattr(item, "prov", None) else None

def split_table(md_table: str, max_chars: int = TABLE_MAX_CHARS):
    """جدول صغير = جزء واحد. الكبير يتقسم بالصفوف مع تكرار الـ header."""
    lines = md_table.strip().split("\n")
    if len(md_table) <= max_chars or len(lines) < 4:
        return [md_table]
    header, rows = lines[:2], lines[2:]
    h_size = sum(len(l) + 1 for l in header)
    parts, cur, size = [], [], h_size
    for r in rows:
        if cur and size + len(r) + 1 > max_chars:
            parts.append("\n".join(header + cur)); cur, size = [], h_size
        cur.append(r); size += len(r) + 1
    if cur: parts.append("\n".join(header + cur))
    return parts


def extract_blocks(doc, doc_title):
    blocks, text_buf, buf_page = [], [], None
    recent, n_tbl = [], 0

    def flush():
        nonlocal text_buf, buf_page
        if text_buf:
            blocks.append({"type": "text", "page": buf_page, "text": "\n\n".join(text_buf)})
        text_buf, buf_page = [], None

    def get_context():
        return " ".join(recent[-3:])[-500:]

    for item, _ in doc.iterate_items():
        page = page_of(item)

        # ---------------- TABLE ----------------
        if isinstance(item, TableItem):
            flush()
            md_table = item.export_to_markdown(doc=doc)
            if not md_table.strip():
                continue
            n_tbl += 1
            caption = (item.caption_text(doc) or "").strip()
            context = get_context()
            desc = describe_table(md_table, caption, doc_title, context) if SUMMARIZE_TABLES else ""
            parts = split_table(md_table)
            for i, part in enumerate(parts, 1):
                tag = f" (part {i}/{len(parts)})" if len(parts) > 1 else ""
                text = f"[Table {n_tbl}{tag}] {caption}\n{desc}\n\n{part}".strip()
                blocks.append({"type": "table", "page": page, "text": text,
                               "atomic": True, "table_id": n_tbl})

        # ---------------- PICTURE ----------------
        elif isinstance(item, PictureItem):
            flush()
            if not DESCRIBE_IMAGES:
                continue
            img = item.get_image(doc)
            if img is None or min(img.size) < MIN_IMG_SIDE:
                continue
            caption = (item.caption_text(doc) or "").strip()
            context = get_context()
            info = describe_image(img, caption, context, doc=doc_title)
            summary = (info.get("summary") or "").strip()
            if "logo_or_decorative" in info["type"] or summary in ("", "N/A"):
                continue
            blocks.append({"type": "figure", "page": page,
                           "text": f"[Figure] {caption}\n{summary}".strip(),
                           "atomic": True})

        # ---------------- TEXT ----------------
        elif isinstance(item, TextItem):
            if item.label in SKIP_LABELS:
                continue
            txt = item.text.strip()
            if not txt:
                continue
            recent.append(txt)
            if isinstance(item, (TitleItem, SectionHeaderItem)):
                txt = "## " + txt
            if buf_page is not None and page != buf_page:
                flush()
            if buf_page is None:
                buf_page = page
            text_buf.append(txt)

    flush()
    return blocks


def build_chunks(doc, doc_title):
    chunks = []
    for b in extract_blocks(doc, doc_title):
        pieces = [b["text"]] if b.get("atomic") else splitter.split_text(b["text"])
        for piece in pieces:
            meta = {"type": b["type"], "page": b["page"], "source": doc_title}
            if "table_id" in b:
                meta["table_id"] = b["table_id"]
            chunks.append({"text": piece, "metadata": meta})
    return chunks

